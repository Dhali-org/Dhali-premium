// Shared release facts: the package version, the published path of
// premium.js, and its subresource-integrity hash.

import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(fileURLToPath(import.meta.url), "../..");
const PKG = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
// Version of premium.js, which names its published path. It is separate from
// the package version: a relay-only fix is a new package release (for the
// wallet to pick up) but must not mint a new premium.js URL.
export const VERSION = PKG.premiumJs;
export const PREMIUM_PATH = `/premium/v${VERSION}/premium.js`;

// Partners load premium.js from the published npm package through a public
// CDN, so the file they run is the one anyone can download and check against
// releases/integrity.json. Every package version contains every frozen
// release, so a URL keeps working whatever package version it names.
export const PACKAGE = PKG.name;
export const PACKAGE_VERSION = PKG.version;
export const CDNS = {
  jsdelivr: "https://cdn.jsdelivr.net/npm",
  unpkg: "https://unpkg.com",
};
export const cdnUrl = (cdn = "jsdelivr", version = VERSION, pkgVersion = PACKAGE_VERSION) =>
  `${CDNS[cdn]}/${PACKAGE}@${pkgVersion}/releases/v${version}/premium.js`;
export const SOURCE = {
  premium: join(ROOT, "src/premium.js"),
  relay: join(ROOT, "src/relay"),
};

// Every published premium.js, frozen at releases/v<version>/premium.js.
// Partners pin these by integrity hash, so every package version must keep
// all of them, and a published file must never change.
export const RELEASES = join(ROOT, "releases");
export const releases = () =>
  existsSync(RELEASES)
    ? readdirSync(RELEASES).filter((d) => /^v\d+\.\d+\.\d+$/.test(d)).sort()
    : [];
// Static relay files. config.js is generated per environment (relayConfig).
export const RELAY_FILES = ["relay.html", "relay.css", "relay.js"];

// Endpoints the relay talks to, per pay.dhali.io deployment. walletUrl is
// relative, so each deployment's relay opens its own wallet. If the relay
// moves to its own origin, make walletUrl absolute (the relay trusts claims
// only from that origin) and build the wallet with
// --dart-define=PREMIUM_RELAY_ORIGIN=<relay origin>.
export const ENVIRONMENTS = {
  prod: {
    walletUrl: "/",
    proxyUrl: "https://run.api.dhali.io",
    metadataUrl: "https://get.api.dhali.io",
  },
  staging: {
    walletUrl: "/",
    proxyUrl: "https://inference-gateway-284340395549.us-central1.run.app",
    metadataUrl: "https://get-api-284340395549.us-central1.run.app",
  },
};

export const relayConfig = (env, cfg = ENVIRONMENTS[env]) =>
  `// Generated by scripts/release.mjs (${env}). Endpoints for the premium-sections relay.
window.DHALI_RELAY_CONFIG = ${JSON.stringify(cfg, null, 2)};
`;

// Content-Security-Policy for relay.html. The relay holds the visitor's claim
// and shares an origin with the wallet, so it may run only its own files and
// talk only to the Dhali proxy and metadata service. No frame-ancestors: any
// partner site must be able to embed it.
export const relayCsp = (env, cfg = ENVIRONMENTS[env]) =>
  [
    "default-src 'none'",
    "script-src 'self'",
    "style-src 'self'",
    `connect-src ${[...new Set([cfg.proxyUrl, cfg.metadataUrl, cfg.devChannelsUrl].filter(Boolean).map((u) => new URL(u).origin))].join(" ")}`,
    "base-uri 'none'",
    "form-action 'none'",
  ].join("; ");

export const integrity = (file = SOURCE.premium) =>
  "sha384-" + createHash("sha384").update(readFileSync(file)).digest("base64");

export const RELEASE_HASHES = join(ROOT, "releases/integrity.json");
export const recordedHashes = () =>
  existsSync(RELEASE_HASHES) ? JSON.parse(readFileSync(RELEASE_HASHES, "utf8")) : {};

export const snippet = ({ src = cdnUrl(), api = "YOUR-API-ID", path = "/your/premium/path" } = {}) =>
  `<script src="${src}"
        integrity="${integrity()}"
        crossorigin="anonymous" type="module" async></script>

<dhali-premium api="${api}" path="${path}">
  <p>Teaser shown before unlocking…</p>
</dhali-premium>`;
